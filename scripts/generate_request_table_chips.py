"""Create the original native-resolution GUI chip templates (requires Pillow).

Run from the repository root: python scripts/generate_request_table_chips.py
These are GUI textures only. Every installed chip is base + level + branch type.
The hand-authored motherboard background is not regenerated by this script.
The current chip PNGs have also been refined by hand; this script recreates the original templates.
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "src/main/resources/assets/logisticspipes/textures/gui/requesttable/chips"
FAMILIES = (("small", 30, 3), ("middle", 39, 4), ("large", 44, 3))
TYPES = ("item_slots", "item_capacity", "fluid_tanks", "fluid_capacity")
PALETTE = {
    "shadow": "#121c19", "edge": "#304238", "face": "#26372e",
    "bevel": "#50634b", "metal": "#676e4b", "contact": "#b1b79b",
    "die": "#1a2e25", "item": "#b1b79b", "fluid": "#5a8177",
    "fluid_light": "#98b8a4",
}


def canvas(size):
    return Image.new("RGBA", (size, size), (0, 0, 0, 0))


def rect(draw, x, y, width, height, color):
    if width > 0 and height > 0:
        draw.rectangle((x, y, x + width - 1, y + height - 1), fill=color)


def die_bounds(size):
    width = size - 16
    return (size - width) // 2, width


def base(size):
    image = canvas(size)
    draw = ImageDraw.Draw(image)
    # Exposed contacts sit outside the package; only the package covers the socket opening.
    for pin in range(4, size - 3, 4):
        rect(draw, pin, 0, 2, 3, PALETTE["metal"])
        rect(draw, pin, 0, 1, 1, PALETTE["contact"])
        rect(draw, pin, size - 3, 2, 3, PALETTE["metal"])
        rect(draw, pin, size - 1, 1, 1, PALETTE["contact"])
        rect(draw, 0, pin, 3, 2, PALETTE["metal"])
        rect(draw, 0, pin, 1, 1, PALETTE["contact"])
        rect(draw, size - 3, pin, 3, 2, PALETTE["metal"])
        rect(draw, size - 1, pin, 1, 1, PALETTE["contact"])
    rect(draw, 2, 2, size - 4, size - 4, PALETTE["shadow"])
    rect(draw, 3, 3, size - 6, size - 6, PALETTE["bevel"])
    rect(draw, 4, 4, size - 8, size - 8, PALETTE["face"])
    rect(draw, 3, size - 4, size - 6, 1, PALETTE["edge"])
    rect(draw, size - 4, 3, 1, size - 6, PALETTE["edge"])
    # Chamfered package corners and one small orientation notch.
    for x, y in ((2, 2), (size - 3, 2), (2, size - 3), (size - 3, size - 3)):
        rect(draw, x, y, 1, 1, (0, 0, 0, 0))
    rect(draw, 4, 4, 2, 2, PALETTE["metal"])
    offset, width = die_bounds(size)
    rect(draw, offset - 1, offset - 1, width + 2, width + 2, PALETTE["shadow"])
    rect(draw, offset, offset, width, width, PALETTE["bevel"])
    rect(draw, offset + 1, offset + 1, width - 2, width - 2, PALETTE["die"])
    if size >= 39:
        for x in (5, size - 7):
            rect(draw, x, size // 2 - 2, 2, 4, PALETTE["metal"])
    if size == 44:
        for y in (5, size - 7):
            rect(draw, size // 2 - 2, y, 4, 2, PALETTE["metal"])
    return image


def level(size, local_level):
    image = canvas(size)
    draw = ImageDraw.Draw(image)
    colors = ("#81977a", "#98aa6b", "#b1b79b", "#c2b687")
    color = colors[local_level - 1]
    # The tier lives on the package rim, leaving the central die for the branch symbol.
    for x, y, w, h in ((7, 5, size - 14, 1), (7, size - 6, size - 14, 1),
                        (5, 7, 1, size - 14), (size - 6, 7, 1, size - 14)):
        rect(draw, x, y, w, h, color)
    rect(draw, 6, 6, 1, 1, color)
    rect(draw, size - 7, 6, 1, 1, color)
    rect(draw, 6, size - 7, 1, 1, color)
    rect(draw, size - 7, size - 7, 1, 1, color)
    # One to four raised contacts make levels readable even without color differences.
    start = (size - (local_level * 3 - 1)) // 2
    for i in range(local_level):
        rect(draw, start + i * 3, 4, 2, 3, color)
        rect(draw, start + i * 3, size - 7, 2, 3, color)
    if local_level >= 2:
        for x in (4, size - 5):
            for y in (9, size - 11):
                rect(draw, x, y, 1, 2, color)
    if local_level >= 3:
        for x in (7, size - 9):
            for y in (7, size - 9):
                rect(draw, x, y, 2, 2, color)
    if local_level == 4:
        for y in (size // 2 - 4, size // 2 + 3):
            rect(draw, 4, y, 3, 1, color)
            rect(draw, size - 7, y, 3, 1, color)
    return image


def branch_type(size, kind):
    image = canvas(size)
    draw = ImageDraw.Draw(image)
    offset, width = die_bounds(size)
    x, y, span = offset + 2, offset + 2, width - 4
    ink = PALETTE["fluid"] if kind.startswith("fluid") else PALETTE["item"]
    # All four types share the die footprint but have their own silicon/etching pattern.
    if kind == "item_slots":
        cell = (span - 3) // 2
        for row in range(2):
            for column in range(2):
                cx, cy = x + 1 + column * (cell + 1), y + 1 + row * (cell + 1)
                rect(draw, cx, cy, cell, cell, ink)
                if cell > 2:
                    rect(draw, cx + 1, cy + 1, cell - 2, cell - 2, PALETTE["face"])
    elif kind == "item_capacity":
        thickness = max(1, (span - 5) // 3)
        for row in range(3):
            cy = y + 1 + row * (thickness + 1)
            rect(draw, x + 1, cy, span - 2, thickness, ink)
            rect(draw, x + span - 3, cy, 1, thickness, PALETTE["metal"])
        rect(draw, x, y + 1, 1, span - 2, PALETTE["metal"])
    elif kind == "fluid_tanks":
        tank = (span - 3) // 2
        for column in range(2):
            cx = x + 1 + column * (tank + 1)
            rect(draw, cx, y + 2, tank, span - 4, ink)
            rect(draw, cx + 1, y + 1, max(1, tank - 2), 1, PALETTE["fluid_light"])
            if tank > 2:
                rect(draw, cx + 1, y + 3, tank - 2, max(1, span // 3), PALETTE["die"])
            rect(draw, cx, y + span - 3, tank, 1, PALETTE["fluid_light"])
    else:
        center = x + span // 2
        rect(draw, center, y + 1, 1, 2, PALETTE["fluid_light"])
        rect(draw, center - 1, y + 3, 3, 2, ink)
        rect(draw, center - 3, y + 5, 7, max(2, span - 7), ink)
        rect(draw, center - 2, y + span - 2, 5, 1, ink)
        rect(draw, center - 2, y + 5, 1, max(1, (span - 7) // 2), PALETTE["fluid_light"])
        if span > 10:
            for cy in range(y + 5, y + span - 2, 3):
                rect(draw, x + span - 3, cy, 2, 1, PALETTE["fluid_light"])
    return image


def main():
    for family, size, levels in FAMILIES:
        directory = DESTINATION / family
        directory.mkdir(parents=True, exist_ok=True)
        base(size).save(directory / "base.png", optimize=True)
        for tier in range(1, levels + 1):
            level(size, tier).save(directory / f"level_{tier}.png", optimize=True)
        for kind in TYPES:
            branch_type(size, kind).save(directory / f"type_{kind}.png", optimize=True)
    print("Saved 3 chip bases, 10 tier overlays and 12 branch overlays at 30x30, 39x39 and 44x44.")


if __name__ == "__main__":
    main()
